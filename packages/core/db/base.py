"""SQLAlchemy declarative base and shared column conventions.

The explicit naming convention matters for Alembic: without it, autogenerated
migrations produce unnamed constraints that cannot be dropped cleanly later.
DATABASE_DESIGN.md §1 mandates it.
"""

from __future__ import annotations

from datetime import datetime
from uuid import UUID

from sqlalchemy import DateTime, MetaData, func
from sqlalchemy.dialects.postgresql import UUID as PGUUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from packages.shared.ids import uuid7

NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)

    # Every timestamp column in the migration is TIMESTAMPTZ. Without this
    # map, a bare `Mapped[datetime]` resolves to SQLAlchemy's default
    # DateTime() -> TIMESTAMP WITHOUT TIME ZONE, which silently disagrees
    # with the database: reads come back naive, comparisons against
    # timezone-aware values raise, and Alembic autogenerate proposes a
    # spurious type change on every run.
    #
    # Setting it here fixes all 57 timestamp columns at once and every
    # column added later. scripts/verify_schema.py asserts it stays true.
    type_annotation_map = {  # noqa: RUF012
        datetime: DateTime(timezone=True),
    }


class UUIDPrimaryKeyMixin:
    id: Mapped[UUID] = mapped_column(PGUUID(as_uuid=True), primary_key=True, default=uuid7)


class TimestampMixin:
    created_at: Mapped[datetime] = mapped_column(server_default=func.now(), nullable=False)
    updated_at: Mapped[datetime] = mapped_column(
        server_default=func.now(), onupdate=func.now(), nullable=False
    )
