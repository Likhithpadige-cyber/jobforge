async def test_the_deciding_human_comes_from_the_session_not_the_request(
    session, demo_profile, demo_job, demo_application, inputs
):
    """Two users exist; the one recorded is the one the endpoint was given.

    There is no request field that could have named the other. This test is
    what makes that claim concrete: the second user is present in the database
    and is never written anywhere, because nothing in the request can reach it.
    """
    _base, _evaluation, facts = inputs
    app_id = demo_application["id"]
    await _ready(session, demo_profile, demo_job, demo_application, facts)
    signed_in = await _actor(session, demo_application)
    other = await _second_user(session)
    await _start(session, app_id, signed_in)

    await _approve(session, app_id, signed_in)

    approval = (await _approvals(session, app_id))[0]
    application = await _application(session, app_id)
    assert approval.decided_by == signed_in.id
    assert application.approved_by == signed_in.id
    assert approval.decided_by != other.id


def test_request_bodies_cannot_name_a_reviewer() -> None:
    """`extra="forbid"` turns an impersonation attempt into a 422.

    Without this the field would simply be ignored, which is safe but silent -
    and a silently ignored `reviewer_user_id` is exactly the kind of thing a
    caller assumes worked.
    """
    for model, payload in [
        (ReviewRequest, {"reviewer_user_id": "x"}),
        (ApproveRequest, {"decided_by": "x"}),
        (RequestChangesRequest, {"note": "fix it", "actor_user_id": "x"}),
    ]:
        with pytest.raises(SchemaValidationError, match=r"(?i)extra"):
            model(**payload)


def _dependencies(endpoint: object) -> list[object]:
    """Every `Depends(...)` callable an endpoint declares, resolved properly.

    `apps.api.routers.resume_review` uses `from __future__ import annotations`,
    so `inspect.signature(...).annotation` is the *source string*
    ("CurrentHumanActor"), not the alias. `get_type_hints(...)` resolves it
    against the module's globals, and `include_extras=True` is what keeps the
    `Annotated[...]` metadata instead of collapsing it to `User`.

    What comes back is the dependency callables themselves, so the assertions
    below can say "this endpoint depends on `current_user`" - the actual
    guarantee - rather than matching an alias name or an object identity that
    a harmless refactor could change.
    """
    from typing import get_args, get_origin, get_type_hints

    from fastapi.params import Depends as DependsParam

    hints = get_type_hints(endpoint, include_extras=True)
    found: list[object] = []
    for annotation in hints.values():
        if get_origin(annotation) is not Annotated:
            continue
        for meta in get_args(annotation)[1:]:
            if isinstance(meta, DependsParam):
                found.append(meta.dependency)
    return found


def test_the_review_endpoints_require_an_authenticated_human() -> None:
    """Identity is a dependency, not a parameter.

    Asserted against the resolved dependency graph so the guarantee cannot be
    quietly removed: every mutating endpoint resolves its human through
    `current_user`, which reads the server-side session and nothing else, and
    none of them accepts a user id under any name.

    The behavioural half of this guarantee is the HTTP test below. This one
    exists because a signature check localises the failure: if the dependency
    were ever dropped, this says which endpoint and why, where the HTTP test
    would only say "still 401 - or is it 401 for some other reason now?".
    """
    import inspect

    from apps.api.deps import current_user, require_csrf

    for endpoint in (start_resume_review, approve_resume, request_resume_changes):
        dependencies = _dependencies(endpoint)
        assert current_user in dependencies, endpoint.__name__
        assert require_csrf in dependencies, endpoint.__name__
        names = set(inspect.signature(endpoint).parameters)
        assert not {"reviewer_user_id", "actor_user_id", "decided_by"} & names


@pytest.mark.parametrize(
    ("path", "body"),
    [
        ("/api/v1/applications/{id}/resume-review", {}),
        ("/api/v1/applications/{id}/resume-review/approve", {}),
        (
            "/api/v1/applications/{id}/resume-review/request-changes",
            {"note": "Please revise."},
        ),
    ],
)
async def test_unauthenticated_review_requests_are_rejected(path, body) -> None:
    """The behavioural proof: no session cookie, no decision. 401, every time.

    Redis and the database are stubbed so the refusal provably comes from the
    authentication path rather than from an unavailable service - a 500 from a
    missing dependency would "pass" a naive status check while proving nothing
    about auth. The session lookup itself is entirely real: no cookie means no
    session, which means no user.

    The app is built here rather than taken from the `app_client` fixture,
    because the overrides have to be installed on the same instance and
    reaching into the fixture's transport for it would couple this test to
    httpx internals.

    Note that no application id helps an attacker. The 401 is raised while
    dependencies are resolved, before any handler code runs, so the workflow
    cannot be reached by guessing a valid application.
    """
    import httpx

    from apps.api.main import create_app
    from packages.core.cache import get_redis
    from packages.core.db import get_session
    from tests.unit.test_auth_sessions import FakeRedis

    app = create_app()
    app.dependency_overrides[get_redis] = lambda: FakeRedis()
    app.dependency_overrides[get_session] = lambda: None

    transport = httpx.ASGITransport(app=app)
    async with httpx.AsyncClient(transport=transport, base_url="http://test") as client:
        response = await client.post(
            path.format(id=uuid7()), json=body, headers={"X-CSRF-Token": "forged"}
        )

    assert response.status_code == 401
    # A forged CSRF header changes nothing: identity is established first, and
    # the body is never even parsed.
    assert "sign in" in response.json()["detail"].lower()


async def test_approve_emits_a_human_approval_granted_event(
    session, demo_profile, demo_job, demo_application, inputs
):
    _base, _evaluation, facts = inputs
    app_id = demo_application["id"]
    await _ready(session, demo_profile, demo_job, demo_application, facts)
    actor = await _actor(session, demo_application)
    await _start(session, app_id, actor)

    await _approve(session, app_id, actor)

    granted = await _events(session, app_id, "approval.granted")
    assert len(granted) == 1
    # EVENTS.md §3.4: no agent may produce this. The envelope enforces it, so
    # an event that exists at all is one a human produced.
    assert granted[0].actor_type == "human"
    assert granted[0].actor_id == str(actor.id)
    assert granted[0].payload["decided_by"] == str(actor.id)

    changed = await _events(session, app_id, "application.status.changed")
    assert changed[-1].payload["to_status"] == "approved"
    assert changed[-1].actor_type == "human"

    # Selected by target status rather than by timestamp: `created_at`
    # defaults to now(), which in PostgreSQL is transaction time, so every
    # history row written in one transaction shares it and "the latest" would
    # be a coin toss.
    history = (
        (
            await session.execute(
                select(ApplicationStatusHistory).where(
                    ApplicationStatusHistory.application_id == app_id,
                    ApplicationStatusHistory.to_status == ApplicationStatus.APPROVED,
                )
            )
        )
        .scalars()
        .all()
    )
    assert len(history) == 1
    assert history[0].actor_type == "human"
    assert history[0].actor_id == str(actor.id)


