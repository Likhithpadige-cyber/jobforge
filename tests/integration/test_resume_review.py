"""C2 - resume review and approval, against a real database.

These tests exist because the interesting parts of C2 are not in Python. The
approval trigger, the `decided_has_actor` CHECK, the one-pending-approval
partial unique index and the append-only history table all live in PostgreSQL,
and a mocked session would let every one of them pass untested.

Review/start/approve endpoints are called directly with the test session.
Request-changes tests exercise the C2 decision service alone; HTTP regeneration
and its authentication/CSRF boundary are covered in test_resume_rework_api.py.

The resume under review is generated by B6 through the same helper the C1 read
tests use, so these tests review a real persisted resume with real claims,
rather than a hand-built row that could be shaped to pass.
"""

