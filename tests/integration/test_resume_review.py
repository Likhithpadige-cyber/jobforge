async def _actor(session, demo_application) -> User:
    """The signed-in human, loaded the way the API dependency loads them."""
    return (
        await session.execute(
            select(User).where(User.id == demo_application["user_id"])
        )
    ).scalar_one()


async def _second_user(session) -> User:
    user = User(id=uuid7(), email=f"second-{uuid7().hex[:8]}@example.invalid", role="owner")
    session.add(user)
    await session.flush()
    return user


async def _ready(session, demo_profile, demo_job, demo_application, facts):
    """An application sitting in `questions_pending` with a clean tailored
    resume - the M9 extraction step already ran (zero questions, the
    ordinary case for a synthetic fixture with no ATS form), same as the
    real pipeline: `resume_ready -> questions_pending` before review ever
    opens."""
    result = await c1._generate(
        session, demo_profile, demo_job, demo_application["id"], facts
    )
    await applications_service.prepare_application(
        session, application_id=demo_application["id"], questions=[]
    )
    await session.flush()
    return result


async def _application(session, application_id) -> Application:
    return (
        await session.execute(
            select(Application).where(Application.id == application_id)
        )
    ).scalar_one()


async def _approvals(session, application_id) -> list[Approval]:
    return list(
        (
            await session.execute(
                select(Approval)
                .where(Approval.application_id == application_id)
                .order_by(Approval.requested_at, Approval.id)
            )
        )
        .scalars()
        .all()
    )


async def _events(session, application_id, type_: str) -> list[Event]:
    return list(
        (
            await session.execute(
                select(Event)
                .where(Event.type == type_, Event.correlation_id == application_id)
                .order_by(Event.occurred_at, Event.id)
            )
        )
        .scalars()
        .all()
    )


async def _history_count(session, application_id) -> int:
    return (
        await session.execute(
            select(func.count(ApplicationStatusHistory.id)).where(
                ApplicationStatusHistory.application_id == application_id
            )
        )
    ).scalar_one()


async def _claims(session, resume_id) -> list[ResumeClaim]:
    return list(
        (
            await session.execute(
                select(ResumeClaim).where(ResumeClaim.resume_id == resume_id)
            )
        )
        .scalars()
        .all()
    )


async def _supersede_with_a_newer_version(session, application_id) -> Resume:
    """Publish a newer tailored version without touching the application.

    This is the regeneration race in miniature: the approval on the table was
    raised for v1, a v2 now exists, and the reviewer's decision is about text
    that is no longer current. Built directly rather than through B6 because
    B6 would move the application, which is precisely the part being isolated.
    """
    current = await service.latest_tailored_resume(session, application_id)
    assert current is not None
    newer = Resume(
        id=uuid7(),
        profile_id=current.profile_id,
        application_id=application_id,
        kind="tailored",
        version=current.version + 1,
        content=dict(current.content),
        summary_text=current.summary_text,
        verification_status="passed",
    )
    session.add(newer)
    await session.flush()
    for claim in await _claims(session, current.id):
        session.add(
            ResumeClaim(
                id=uuid7(),
                resume_id=newer.id,
                section=claim.section,
                path=claim.path,
                claim_text=claim.claim_text,
                fact_ids=list(claim.fact_ids),
                numerals_used=list(claim.numerals_used),
                verdict=claim.verdict,
                verdict_reason=claim.verdict_reason,
                verified_at=claim.verified_at,
            )
        )
    await session.flush()
    return newer


async def _start(session, application_id, actor):
    return await start_resume_review(
        application_id, ReviewRequest(), session, actor, None
    )


async def _approve(session, application_id, actor, note=None):
    return await approve_resume(
        application_id, ApproveRequest(decision_note=note), session, actor, None
    )


async def _request_changes(session, application_id, actor, note):
    state = await service.request_changes(
        session, application_id=application_id, actor=actor, note=note
    )
    await session.commit()
    return state


async def _historical_rework_decision(session, application_id, actor_id):
    """Create an older decision through the same pending-to-decided DB transition."""
    approval_id = uuid7()
    await session.execute(
        text(
            "INSERT INTO approvals (id, application_id, kind, status, "
            "subject_snapshot, requested_at) VALUES "
            "(:id, :app, 'resume', 'pending', '{}'::jsonb, "
            "now() - interval '10 days')"
        ),
        {"id": approval_id, "app": application_id},
    )
    await session.execute(
        text(
            "UPDATE approvals SET status = 'changes_requested', "
            "decided_by = :actor, decided_at = now(), "
            "changes_requested = 'historical decision' WHERE id = :id"
        ),
        {"id": approval_id, "actor": actor_id},
    )
    return approval_id


