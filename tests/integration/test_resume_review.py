async def test_entering_review_moves_to_awaiting_approval(
    session, demo_profile, demo_job, demo_application, inputs
):
    _base, _evaluation, facts = inputs
    app_id = demo_application["id"]
    generated = await _ready(session, demo_profile, demo_job, demo_application, facts)
    actor = await _actor(session, demo_application)

    state = await _start(session, app_id, actor)

    assert state.application_status is ApplicationStatus.AWAITING_APPROVAL
    assert state.review_status == "in_review"
    assert state.resume_id == generated.resume_id
    assert (await _application(session, app_id)).status is (
        ApplicationStatus.AWAITING_APPROVAL
    )


async def test_pending_approval_is_bound_to_the_exact_resume_and_version(
    session, demo_profile, demo_job, demo_application, inputs
):
    """The binding is the whole point of `subject_snapshot`."""
    _base, _evaluation, facts = inputs
    app_id = demo_application["id"]
    generated = await _ready(session, demo_profile, demo_job, demo_application, facts)
    actor = await _actor(session, demo_application)

    await _start(session, app_id, actor)

    approvals = await _approvals(session, app_id)
    assert len(approvals) == 1
    approval = approvals[0]
    assert approval.kind is ApprovalKind.RESUME
    assert approval.status is ApprovalStatus.PENDING
    assert approval.subject_snapshot["resume_id"] == str(generated.resume_id)
    assert approval.subject_snapshot["resume_version"] == generated.version
    assert approval.decided_by is None
    assert approval.decided_at is None
    # The tally that justified opening review is kept with the request.
    assert approval.guardrail_flags["verdict_counts"]["supported"] == 3
    assert approval.guardrail_flags["verdict_counts"]["unsupported"] == 0


async def test_entering_review_emits_approval_requested_and_status_changed(
    session, demo_profile, demo_job, demo_application, inputs
):
    _base, _evaluation, facts = inputs
    app_id = demo_application["id"]
    await _ready(session, demo_profile, demo_job, demo_application, facts)
    actor = await _actor(session, demo_application)
    before = await _history_count(session, app_id)

    await _start(session, app_id, actor)

    requested = await _events(session, app_id, "approval.requested")
    assert len(requested) == 1
    assert requested[0].actor_type == "human"
    assert requested[0].actor_id == str(actor.id)
    assert requested[0].payload["human_required_answers"] == 0
    assert await _history_count(session, app_id) == before + 1

    changed = await _events(session, app_id, "application.status.changed")
    assert changed[-1].payload["to_status"] == "awaiting_approval"
    assert changed[-1].actor_type == "human"


async def test_entering_review_is_idempotent(
    session, demo_profile, demo_job, demo_application, inputs
):
    """A double-click must not raise a second approval or a second event."""
    _base, _evaluation, facts = inputs
    app_id = demo_application["id"]
    await _ready(session, demo_profile, demo_job, demo_application, facts)
    actor = await _actor(session, demo_application)

